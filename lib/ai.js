const { GoogleGenerativeAI } = require("@google/generative-ai");
const config = require("../config");

const genAI = new GoogleGenerativeAI(config.GEMINI_API_KEY);
const model = genAI.getGenerativeModel({ model: "gemini-pro" });

/**
 * AI Logic for Starry MD
 */
module.exports = {
    /**
     * Generate content using Gemini with History Support
     */
    generateContent: async (prompt, personaType = 'default', history = []) => {
        try {
            const systemPrompt = config.PERSONAS[personaType] || config.PERSONAS.default;

            // Start Chat with History
            const chat = model.startChat({
                history: history,
                generationConfig: {
                    maxOutputTokens: 500,
                },
            });

            const fullPrompt = `${systemPrompt}\n\nUser: ${prompt}`;
            const result = await chat.sendMessage(fullPrompt);
            const response = await result.response.text();

            // Add persona flair
            const flairs = {
                rude: "\n\n_Don't expect me to be this helpful next time. 🙄_",
                tech: "\n\n_Generated by Starry-Gemini-Pro Link._",
                uwu: "\n\n_Hope that helped you, senpai! (≧◡≦) ♡_",
                genz: "\n\n_No cap, hope this helps. fr fr. 💅_",
                mom: "\n\n_Take care of yourself, sweetie! 💕_",
                pirate: "\n\n_Fair winds and following seas, Matey! 🏴‍☠️_",
                default: "\n\n🌠 *Starry AI Intelligence*"
            };

            return response + (flairs[personaType] || flairs.default);
        } catch (error) {
            console.error("AI Generation Error:", error);
            return "❌ Error: I couldn't process that AI request right now. Check your GEMINI_API_KEY.";
        }
    }
};
